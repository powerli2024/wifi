#!/usr/bin/env python3
"""Offline checks for the project's authored Markdown (Python standard library only).

This is a deliberately bounded Markdown parser, not a complete CommonMark engine.
Run: python tools/check_docs.py --root . --json /path/to/result.json
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
import os
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit


EXCLUDED_DIRS = frozenset({
    ".git", ".gradle", ".local", ".idea", ".venv", "__pycache__",
    "build", "dist", "verification", "fixtures", "node_modules",
    "vendor", "third_party", "third-party", "thirdparty", "generated",
})
LIMITATIONS = [
    "Checks a Markdown subset, not full CommonMark/GFM rendering.",
    "HTML href/src attributes, MDX, tables generated by scripts, and bare URLs are not parsed.",
    "Reference definitions must have their destination and optional title on one line.",
    "Headings support ATX/setext text and basic GitHub-style duplicate slugs; complex HTML headings may differ.",
    "Only fragments targeting Markdown are checked; fragments in PDFs, source files, and HTML are not checked.",
    "External links are counted but never fetched; network reachability is not verified.",
    "Indented code blocks and deeply nested container/fence syntax are not interpreted as full CommonMark.",
    "Navigation is graph reachability from README.md and docs/README.md, not a reading-order or usability judgment.",
    "Migration originalSha256 is validated as metadata syntax only; rewritten targets need not retain the original hash.",
    "Leading-slash local links are interpreted relative to --root; machine-specific drive/file URLs are rejected.",
]


@dataclass(frozen=True)
class Link:
    target: str
    line: int
    kind: str = "link"


def blank(text: str) -> str:
    return "".join("\n" if char == "\n" else " " for char in text)


def strip_code(text: str, inline: bool = True) -> str:
    """Mask fenced/code-span content while keeping offsets and line numbers."""
    result = []
    fence = None
    for line in text.splitlines(keepends=True):
        marker = re.match(r"^ {0,3}(`{3,}|~{3,})(.*)$", line.rstrip("\r\n"))
        if fence:
            result.append(blank(line))
            if marker and marker[1][0] == fence[0] and len(marker[1]) >= fence[1] and not marker[2].strip():
                fence = None
        elif marker and not (marker[1][0] == "`" and "`" in marker[2]):
            fence = (marker[1][0], len(marker[1]))
            result.append(blank(line))
        else:
            result.append(line)
    value = "".join(result)
    if not inline:
        return value
    chars = list(value)
    offset = 0
    while offset < len(value):
        if value[offset] != "`" or escaped(value, offset):
            offset += 1
            continue
        run = re.match(r"`+", value[offset:])[0]
        end = offset + len(run)
        closing = re.search(r"(?<!`)" + re.escape(run) + r"(?!`)", value[end:])
        if closing:
            stop = end + closing.end()
            chars[offset:stop] = blank(value[offset:stop])
            offset = stop
        else:
            offset = end
    return "".join(chars)


def escaped(text: str, position: int) -> bool:
    start = position - 1
    while start >= 0 and text[start] == "\\":
        start -= 1
    return (position - start - 1) % 2 == 1


def unescape(value: str) -> str:
    return re.sub(r"\\([!\"#$%&'()*+,\-./:;<=>?@\[\\\]^_`{|}~])", r"\1", value)


def label_key(label: str) -> str:
    return " ".join(unescape(label).split()).casefold()


def destination(value: str) -> str | None:
    """Read a destination with an optional quoted or parenthesized title."""
    value = value.strip()
    if not value:
        return ""
    if value.startswith("<"):
        end = next((i for i in range(1, len(value)) if value[i] == ">" and not escaped(value, i)), -1)
        if end < 0 or "\n" in value[:end]:
            return None
        target, tail = value[1:end], value[end + 1:].strip()
    else:
        depth, end = 0, 0
        for end, char in enumerate(value):
            if escaped(value, end):
                continue
            if char.isspace() and depth == 0:
                break
            if char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
                if depth < 0:
                    return None
        else:
            end = len(value)
        if depth:
            return None
        target, tail = value[:end], value[end:].strip()
    if tail:
        pairs = {'"': '"', "'": "'", "(": ")"}
        if tail[0] not in pairs or len(tail) < 2 or tail[-1] != pairs[tail[0]]:
            return None
    return unescape(target)


def closing_bracket(text: str, start: int) -> int | None:
    depth = 1
    for pos in range(start + 1, len(text)):
        if escaped(text, pos):
            continue
        if text[pos] == "[":
            depth += 1
        elif text[pos] == "]":
            depth -= 1
            if depth == 0:
                return pos
    return None


def closing_parenthesis(text: str, start: int) -> int | None:
    depth, angle, quote = 1, False, None
    for pos in range(start + 1, len(text)):
        char = text[pos]
        if escaped(text, pos):
            continue
        if quote:
            if char == quote:
                quote = None
        elif angle:
            if char == ">":
                angle = False
        elif char == "<":
            angle = True
        elif char in "\"'" and pos > start + 1 and text[pos - 1].isspace():
            quote = char
        elif char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth == 0:
                return pos
    return None


def extract_links(text: str) -> tuple[list[Link], list[dict]]:
    clean = strip_code(text)
    clean = re.sub(r"<!--[\s\S]*?-->", lambda match: blank(match[0]), clean)
    definitions = {}
    spans = []
    problems = []
    for match in re.finditer(r"(?m)^ {0,3}\[([^\]\n]+)\]:[ \t]*(.*)$", clean):
        target = destination(match[2])
        if target is not None:
            definitions.setdefault(label_key(match[1]), target)
            spans.append(match.span())
    chars = list(clean)
    for start, end in spans:
        chars[start:end] = blank(clean[start:end])
    clean = "".join(chars)
    links = []
    inline_spans = []
    pos = 0
    while pos < len(clean):
        if clean[pos] != "[" or escaped(clean, pos):
            pos += 1
            continue
        end = closing_bracket(clean, pos)
        if end is None:
            pos += 1
            continue
        line = clean.count("\n", 0, pos) + 1
        label = clean[pos + 1:end]
        kind = "image" if pos > 0 and clean[pos - 1] == "!" and not escaped(clean, pos - 1) else "link"
        after = end + 1
        if after < len(clean) and clean[after] == "(":
            stop = closing_parenthesis(clean, after)
            if stop is not None:
                target = destination(clean[after + 1:stop])
                if target is not None:
                    links.append(Link(target, line, kind))
                    inline_spans.append((pos, stop + 1))
                else:
                    problems.append({"code": "unsupported_destination", "line": line, "severity": "warning", "message": "Cannot parse link destination/title."})
                # Examine nested image markup in a linked image as well.
                if "![" in label:
                    nested, nested_problems = extract_links(label)
                    links.extend(Link(item.target, line + item.line - 1, item.kind) for item in nested)
                    problems.extend(dict(item, line=line + item["line"] - 1) for item in nested_problems)
                pos = stop + 1
                continue
        elif after < len(clean) and clean[after] == "[":
            stop = closing_bracket(clean, after)
            if stop is not None:
                key = label_key(clean[after + 1:stop] or label)
                if key in definitions:
                    links.append(Link(definitions[key], line, kind))
                else:
                    problems.append({"code": "undefined_reference", "line": line, "severity": "warning", "message": f"Undefined explicit reference [{key}]; Markdown may render this as plain text."})
                pos = stop + 1
                continue
        key = label_key(label)
        if key in definitions:
            links.append(Link(definitions[key], line, kind))
        pos = end + 1
    for match in re.finditer(r"<((?:https?://|mailto:)[^<>\s]+)>", clean, re.IGNORECASE):
        if not any(start <= match.start() < end for start, end in inline_spans):
            links.append(Link(match[1], clean.count("\n", 0, match.start()) + 1, "autolink"))
    return links, problems


def heading_anchors(text: str) -> set[str]:
    clean = strip_code(text, inline=False)
    titles = []
    lines = clean.splitlines()
    for index, line in enumerate(lines):
        match = re.match(r"^ {0,3}#{1,6}[ \t]+(.*?)(?:[ \t]+#+[ \t]*)?$", line)
        if match:
            titles.append(match[1])
        elif index and re.match(r"^ {0,3}(?:=+|-+)[ \t]*$", line) and lines[index - 1].strip():
            # Exclude obvious lists/rules; this is a simple setext subset.
            if not re.match(r"^\s*(?:[-*+]\s|#{1,6}\s)", lines[index - 1]):
                titles.append(lines[index - 1].strip())
    anchors = set(re.findall(r"<a\b[^>]*\b(?:id|name)=[\"']([^\"']+)[\"']", clean, re.IGNORECASE))
    counts = {}
    for title in titles:
        title = re.sub(r"!?\[([^\]]+)\]\([^)]*\)", r"\1", title)
        title = re.sub(r"<[^>]+>", "", title)
        title = unescape(title).replace("`", "")
        slug = re.sub(r"[^\w\- ]", "", title.lower(), flags=re.UNICODE).replace(" ", "-")
        number = counts.get(slug, 0)
        candidate = slug if number == 0 else f"{slug}-{number}"
        while candidate in anchors:
            number += 1
            candidate = f"{slug}-{number}"
        counts[slug] = number + 1
        anchors.add(candidate)
    return anchors


def authored_markdown(root: Path) -> list[Path]:
    result = []
    for directory, names, files in os.walk(root, followlinks=False):
        names[:] = sorted(name for name in names if name.casefold() not in EXCLUDED_DIRS and not Path(directory, name).is_symlink())
        result.extend(Path(directory, name) for name in sorted(files) if name.lower().endswith(".md"))
    return result


def locate_case(root: Path, expected: Path) -> tuple[Path | None, bool]:
    """Find a target component by component, including on case-insensitive hosts."""
    relative = os.path.relpath(os.path.abspath(expected), root)
    current = root
    mismatch = False
    for part in Path(relative).parts:
        if part in ("", "."):
            continue
        if part == "..":
            current = current.parent
            continue
        if not current.is_dir():
            return None, mismatch
        try:
            names = [child.name for child in current.iterdir()]
        except OSError:
            return None, mismatch
        if part in names:
            current /= part
        else:
            alternatives = sorted(name for name in names if name.casefold() == part.casefold())
            if not alternatives:
                return None, mismatch
            current /= alternatives[0]
            mismatch = True
    return (current if current.exists() else None), mismatch


def validate(root: Path, migration_manifest: Path | None = None) -> dict:
    root = root.resolve()
    issues = []
    counts = {"markdownFiles": 0, "links": 0, "localLinks": 0, "externalLinks": 0, "images": 0, "anchorsChecked": 0, "migrationEntries": 0}
    external = []
    files = authored_markdown(root)
    documents = {}
    for path in files:
        try:
            documents[path.resolve()] = path.read_text(encoding="utf-8-sig")
        except (OSError, UnicodeError) as error:
            issues.append({"code": "markdown_read_error", "severity": "error", "file": path.relative_to(root).as_posix(), "message": str(error)})
    counts["markdownFiles"] = len(files)
    graph = {path: set() for path in documents}
    anchor_cache = {path: heading_anchors(text) for path, text in documents.items()}

    def issue(code, file, message, line=None, target=None, severity="error"):
        item = {"code": code, "severity": severity, "file": file, "message": message}
        if line is not None:
            item["line"] = line
        if target is not None:
            item["target"] = target
        issues.append(item)

    for source, text in documents.items():
        source_name = source.relative_to(root).as_posix()
        links, problems = extract_links(text)
        issues.extend(dict(problem, file=source_name) for problem in problems)
        for link in links:
            counts["links"] += 1
            counts["images"] += int(link.kind == "image")
            if re.match(r"^[A-Za-z]:[/\\]", link.target) or link.target.lower().startswith("file:"):
                counts["localLinks"] += 1
                issue("absolute_local_path", source_name, "Use a portable repository-relative path instead of a drive or file URL.", link.line, link.target)
                continue
            try:
                url = urlsplit(link.target)
            except ValueError as error:
                issue("invalid_url", source_name, str(error), link.line, link.target)
                continue
            if url.scheme or url.netloc or link.target.startswith("//"):
                counts["externalLinks"] += 1
                external.append({"file": source_name, "line": link.line, "target": link.target})
                continue
            counts["localLinks"] += 1
            decoded = unquote(url.path)
            if "\x00" in decoded:
                issue("invalid_local_path", source_name, "Decoded path contains NUL.", link.line, link.target)
                continue
            if "\\" in decoded:
                issue("nonportable_separator", source_name, "Use forward slashes in Markdown paths.", link.line, link.target)
                decoded = decoded.replace("\\", "/")
            expected = (root / decoded.lstrip("/")) if decoded.startswith("/") else (source.parent / decoded if decoded else source)
            actual, mismatch = locate_case(root, expected)
            if actual is None:
                issue("missing_target", source_name, "Local target does not exist.", link.line, link.target)
                continue
            if mismatch:
                issue("case_mismatch", source_name, f"Path capitalization differs from disk: {os.path.relpath(actual, source.parent).replace(os.sep, '/')}", link.line, link.target)
            if actual.is_dir():
                index, _ = locate_case(root, actual / "README.md")
                if index:
                    actual = index
            canonical = actual.resolve()
            if canonical in graph and link.kind != "image":
                graph[source].add(canonical)
            if url.fragment and actual.suffix.lower() == ".md":
                counts["anchorsChecked"] += 1
                if canonical not in anchor_cache:
                    try:
                        anchor_cache[canonical] = heading_anchors(actual.read_text(encoding="utf-8-sig"))
                    except (OSError, UnicodeError) as error:
                        issue("anchor_read_error", source_name, str(error), link.line, link.target)
                        continue
                if unquote(url.fragment) not in anchor_cache[canonical]:
                    issue("missing_anchor", source_name, "Heading or explicit anchor was not found using the supported anchor rules.", link.line, link.target)

    roots = [path.resolve() for path in (root / "README.md", root / "docs" / "README.md") if path.resolve() in graph]
    reached = set()
    pending = list(roots)
    while pending:
        current = pending.pop()
        if current in reached:
            continue
        reached.add(current)
        pending.extend(graph[current] - reached)
    docs = {path for path in documents if path.relative_to(root).parts[0] == "docs"}
    if docs and not roots:
        issue("missing_navigation_root", ".", "Neither README.md nor docs/README.md exists.")
    for path in sorted(docs - reached):
        issue("unreachable_document", path.relative_to(root).as_posix(), "Document is unreachable from README.md or docs/README.md.")

    if migration_manifest:
        try:
            manifest = json.loads(migration_manifest.read_text(encoding="utf-8-sig"))
            entries = manifest.get("entries") if isinstance(manifest, dict) else None
            if not isinstance(entries, list):
                raise ValueError("Expected object with an entries array.")
            for number, entry in enumerate(entries):
                counts["migrationEntries"] += 1
                if not isinstance(entry, dict) or not isinstance(entry.get("targetPath"), str) or not entry["targetPath"]:
                    issue("invalid_migration_entry", str(migration_manifest), f"Entry {number}: nonempty targetPath is required.")
                    continue
                target = Path(entry["targetPath"])
                actual, mismatch = locate_case(root, target if target.is_absolute() else root / target)
                if actual is None:
                    issue("migration_target_missing", str(migration_manifest), f"Entry {number}: target does not exist.", target=entry["targetPath"])
                elif mismatch:
                    issue("migration_target_case_mismatch", str(migration_manifest), f"Entry {number}: target capitalization differs from disk.", target=entry["targetPath"])
                digest = entry.get("originalSha256")
                if digest is not None and not re.fullmatch(r"[a-fA-F0-9]{64}", str(digest)):
                    issue("invalid_original_hash", str(migration_manifest), f"Entry {number}: originalSha256 must contain 64 hexadecimal characters.")
        except (OSError, UnicodeError, ValueError) as error:
            issue("invalid_migration_manifest", str(migration_manifest), str(error))

    errors = sum(item["severity"] == "error" for item in issues)
    warnings = sum(item["severity"] == "warning" for item in issues)
    return {
        "schemaVersion": 1, "root": str(root), "ok": errors == 0,
        "counts": dict(counts, errors=errors, warnings=warnings),
        "navigation": {"roots": [path.relative_to(root).as_posix() for path in roots], "reachableMarkdownFiles": len(reached), "unreachableDocs": len(docs - reached)},
        "excludedDirectories": sorted(EXCLUDED_DIRS), "externalLinks": external,
        "issues": issues, "limitations": LIMITATIONS,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--json", type=Path, metavar="OUTPUT", help="Write the complete machine-readable result.")
    parser.add_argument("--migration-manifest", type=Path)
    args = parser.parse_args()
    if not args.root.is_dir():
        parser.error("--root must be an existing directory")
    result = validate(args.root, args.migration_manifest)
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    counts = result["counts"]
    print(f"Docs: {counts['markdownFiles']}; local links: {counts['localLinks']}; external links (not fetched): {counts['externalLinks']}; errors: {counts['errors']}; warnings: {counts['warnings']}")
    for item in result["issues"]:
        location = item["file"] + (f":{item['line']}" if "line" in item else "")
        print(f"{item['severity'].upper()} {location} [{item['code']}] {item['message']}" + (f" ({item['target']})" if "target" in item else ""))
    print("Parser scope: bounded Markdown subset; external URLs and non-Markdown fragments are not verified. See JSON limitations.")
    return 0 if result["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
